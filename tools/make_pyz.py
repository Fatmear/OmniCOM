"""Build a no-exe distribution: a ``.pyz`` archive plus a shortcut-friendly launcher.

Corporate endpoint security blocks the exe PyInstaller produces ("移远安全助手"
deletes it), while the Python from the Microsoft Store runs fine.  The reason is
that PyInstaller wraps everything in an **unsigned, self-extracting bootloader**
- exactly the shape a packer-based detector looks for - whereas ``pythonw.exe``
from the Store is signed by Microsoft.

So this script stops shipping a new executable at all (R-019 / R-083):

    dist/OmniCOM/
        OmniCOM.pyz        our own code, one zip (also readable as source)
        OmniCOM.cmd        double-click / shortcut target
        assets/  plugins/  the same files the source tree uses
        omnicom-data/      created on first run (logs, commands, plugins)

The launcher runs ``pythonw`` (no console) or ``python`` (console, for debugging)
from PATH; nothing is compiled, nothing is self-extracting, so there is nothing
for an AV signature to match.

    python tools/make_pyz.py            # build dist/OmniCOM
    python tools/make_pyz.py --check    # build, then run the packaged --selftest

For a folder the *user* can run without installing anything, use
``tools/make_dist.py``: it calls this module for the archive and adds the bundled
runtime and dependencies around it (R-083).
"""

from __future__ import annotations

import argparse
import compileall
import shutil
import subprocess
import sys
import zipapp
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAME = "OmniCOM"
LAUNCHER = """@echo off
rem OmniCOM launcher (no exe on purpose - see R-019 / R-083).
rem Double-click this, or point a desktop shortcut at it.
setlocal
cd /d "%~dp0"
set PYTHONIOENCODING=utf-8
where pythonw >nul 2>nul
if errorlevel 1 (
  python "OmniCOM.pyz" %*
) else (
  start "" pythonw "OmniCOM.pyz" %*
)
endlocal
"""
CONSOLE_LAUNCHER = """@echo off
rem OmniCOM with a console window, so Python/Qt errors stay visible.
setlocal
cd /d "%~dp0"
set PYTHONIOENCODING=utf-8
python "OmniCOM.pyz" %*
echo.
echo [OmniCOM] exited with code %ERRORLEVEL%
pause
endlocal
"""
MAIN = '''"""OmniCOM zipapp entry point (generated by tools/make_pyz.py)."""

from __future__ import annotations

import sys

from omnicom.ui import main

if __name__ == "__main__":
    raise SystemExit(main())
'''


def build(target: Path, *, stubs_only: bool = False) -> Path:
    staging = target / "_pyz"
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)

    for source in ("omnicom",):
        shutil.copytree(ROOT / source, staging / source,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    (staging / "__main__.py").write_text(MAIN, encoding="utf-8")
    compileall.compile_dir(staging, quiet=1, force=True)

    archive = target / f"{NAME}.pyz"
    zipapp.create_archive(staging, archive, interpreter="/usr/bin/env python3",
                          compressed=True)
    shutil.rmtree(staging)

    for folder in ("assets", "plugins"):
        destination = target / folder
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(ROOT / folder, destination,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    # The logo has to sit beside the archive: "About" and the window icon read it.
    for asset in ("logo.png", "README.md", "README.en.md", "LICENSE"):
        if (ROOT / asset).is_file():
            shutil.copy2(ROOT / asset, target / asset)
    # The CLI contract has to travel with the program: an agent that only has the
    # unzipped folder must be able to learn the whole interface from it (R-086).
    for doc in ("CLI.md", "AI-GUIDE.md"):
        source = ROOT / "docs" / doc
        if source.is_file():
            shutil.copy2(source, target / doc)

    (target / f"{NAME}.cmd").write_text(LAUNCHER, encoding="utf-8", newline="\r\n")
    (target / "console.cmd").write_text(CONSOLE_LAUNCHER, encoding="utf-8",
                                        newline="\r\n")
    (target / "HOW-TO-RUN.txt").write_text(
        "OmniCOM - 免 exe 运行说明\r\n"
        "========================\r\n"
        "\r\n"
        "1) 双击 OmniCOM.cmd 即可启动（无命令行窗口）。\r\n"
        "2) 想放到桌面：右键 OmniCOM.cmd -> 发送到 -> 桌面快捷方式，\r\n"
        "   再到快捷方式属性里把「运行方式」设为「最小化」，图标随便换。\r\n"
        "3) 需要看报错时用 console.cmd。\r\n"
        "4) 首次运行会生成 omnicom-data\\ 目录（记录、命令、插件）。\r\n"
        "\r\n"
        "OmniCOM - running without an exe\r\n"
        "================================\r\n"
        "1) Double-click OmniCOM.cmd.\r\n"
        "2) Desktop icon: right-click OmniCOM.cmd -> Send to -> Desktop (create\r\n"
        "   shortcut), then set the shortcut's Run option to Minimized.\r\n"
        "3) Use console.cmd when you need to read a traceback.\r\n"
        "4) omnicom-data\\ appears on the first run.\r\n",
        encoding="utf-8",
        newline="",
    )
    print(f"built {archive} ({archive.stat().st_size / 1024:.0f} KB)")
    return archive


def verify(target: Path) -> int:
    """Run the packaged app headless so a broken archive never ships."""
    python = shutil.which("python") or sys.executable
    result = subprocess.run([python, str(target / f"{NAME}.pyz"), "--selftest"],
                            cwd=target, capture_output=True, text=True,
                            encoding="utf-8", errors="replace", timeout=180)
    output = ((result.stdout or "") + (result.stderr or "")).strip()
    print(output[-1500:] if output else "(no output)")
    return 0 if result.returncode == 0 else result.returncode


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "dist" / NAME))
    parser.add_argument("--check", action="store_true",
                        help="run the packaged --selftest afterwards")
    options = parser.parse_args()

    target = Path(options.out).resolve()
    target.mkdir(parents=True, exist_ok=True)
    build(target)
    if options.check:
        return verify(target)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
